/// 计算器页面（显示屏、按键提示、函数库、历史记录）的界面文案。
///
/// 与工具页的 `<tool>_strings.dart` 同一套写法：用 `required` 具名字段列出
/// 全部文案，漏一种语言直接编译报错。带参数的句子写成 `{0}` 模板，用
/// [fill] 填充，避免在代码里拼句子（日语 / 西语的语序不同）。
class CalcStrings {
  const CalcStrings({
    required this.keyboardHint,
    required this.historyShort,
    required this.clear,
    required this.historyTitle,
    required this.historyEmpty,
    required this.copyEntryTooltip,
    required this.copyLatex,
    required this.copyResult,
    required this.latexCopied,
    required this.resultCopied,
    required this.latexWithResultCopied,
    required this.latexFailed,
    required this.angleTooltip,
    required this.memoryClearTooltip,
    required this.insertAnsTooltip,
    required this.functionLibrary,
    required this.copyTooltip,
    required this.copyLatexWithResult,
    required this.inputHint,
    required this.previewHint,
    required this.functionsIntro,
    required this.angleDegrees,
    required this.angleRadians,
    required this.categoryTrig,
    required this.categoryHyperbolic,
    required this.categoryExpLog,
    required this.categoryPowerRoot,
    required this.categoryRounding,
    required this.categoryCombinatorics,
    required this.categoryCalculus,
    required this.categoryMisc,
    required this.functionDescriptions,
    required this.sumDescription,
    required this.prodDescription,
    required this.integrateDescription,
    required this.diffDescription,
  });

  /// 「支持键盘输入：回车计算，↑↓ 翻历史」。
  final String keyboardHint;

  /// 窄屏底栏上的短标题（「历史」）。
  final String historyShort;
  final String clear;
  final String historyTitle;

  /// 历史面板空状态：换行用 `\n`。
  final String historyEmpty;
  final String copyEntryTooltip;
  final String copyLatex;
  final String copyResult;
  final String latexCopied;
  final String resultCopied;
  final String latexWithResultCopied;

  /// 这条记录无法转换为 LaTeX。
  final String latexFailed;

  /// 「切换角度单位（当前：{0}）」。
  final String angleTooltip;
  final String memoryClearTooltip;
  final String insertAnsTooltip;
  final String functionLibrary;
  final String copyTooltip;
  final String copyLatexWithResult;
  final String inputHint;
  final String previewHint;
  final String functionsIntro;

  final String angleDegrees;
  final String angleRadians;

  final String categoryTrig;
  final String categoryHyperbolic;
  final String categoryExpLog;
  final String categoryPowerRoot;
  final String categoryRounding;
  final String categoryCombinatorics;
  final String categoryCalculus;
  final String categoryMisc;

  /// 函数说明（按内置函数名，没有翻译时回落到 `lib/core/builtins.dart` 里的中文）。
  final Map<String, String> functionDescriptions;

  /// 特殊形式（求和 / 连乘 / 积分 / 求导）的说明。
  final String sumDescription;
  final String prodDescription;
  final String integrateDescription;
  final String diffDescription;

  /// 角度模式名称（数据层的 `AngleMode` 只有中文）。
  String angleLabel(AngleMode mode) =>
      mode == AngleMode.degrees ? angleDegrees : angleRadians;

  /// 某个内置函数的一句话说明，[fallback] 是数据层的简体中文说明。
  String functionDescription(String name, String fallback) =>
      functionDescriptions[name] ?? fallback;
}

